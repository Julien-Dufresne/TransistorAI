
"""
TransistorAI - Day 5
Translation quality metrics.

This module evaluates model predictions using:
1. BLEU: word n-gram overlap with reference translations.
2. chrF: character n-gram precision and recall.

Both metrics are calculated at corpus level.
"""

import sacrebleu


def calculate_metrics(predictions, references):
    """
    Calculate corpus-level BLEU and chrF scores.

    Parameters
    ----------
    predictions : list[str]
        Translations generated by the pretrained model.

    references : list[str]
        Human reference translations, in matching order.

    Returns
    -------
    dict
        Scores, sentence count and reproducibility signatures.
    """

    # Every prediction must have a corresponding reference.
    if len(predictions) != len(references):
        raise ValueError(
            "Predictions and references have different lengths."
        )

    # Prevent evaluating empty datasets.
    if not predictions:
        raise ValueError("Cannot evaluate an empty dataset.")

    # Create the BLEU metric.
    # tokenize='13a' fixes the tokenization method.
    bleu_metric = sacrebleu.metrics.BLEU(
        tokenize="13a"
    )

    # Create chrF with standard character-level settings.
    # word_order=0 means character n-grams only.
    chrf_metric = sacrebleu.metrics.CHRF(
        char_order=6,
        word_order=0,
        beta=2,
    )

    # The outer list represents multiple reference corpora.
    # Here we have one reference per source sentence.
    bleu_result = bleu_metric.corpus_score(
        predictions, [references]
    )

    chrf_result = chrf_metric.corpus_score(
        predictions, [references]
    )

    return {
        "bleu": round(bleu_result.score, 4),
        "chrf": round(chrf_result.score, 4),
        "sentence_count": len(predictions),
        "bleu_signature": str(bleu_metric.get_signature()),
        "chrf_signature": str(chrf_metric.get_signature()),
        "sacrebleu_version": sacrebleu.__version__,
    }
